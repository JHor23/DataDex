    fun forName(name: String): String? {
        val normalized = name.lowercase().trim()
        return descriptions[normalized]
            ?: descriptions[normalized.replace("-", " ")]
    }

    fun resolveDescription(ability: PokemonAbilityInfo): String {
        if (ability.description.isNotBlank()) return ability.description
        return forName(ability.name) ?: "Special battle trait active while this Pokémon is on the field."
    }
